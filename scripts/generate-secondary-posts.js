function generateMarkdown(p) {
  const sectionsContent = p.sections.map(s => `## ${s.heading}\n\n${s.content}`).join("\n\n");
  
  const faqSchema = {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    "mainEntity": p.faq.map(item => ({
      "@type": "Question",
      "name": item.q,
      "acceptedAnswer": {
        "@type": "Answer",
        "text": item.a
      }
    }))
  };

  const faqContent = `## 常见问题解答 (FAQ)\n\n` + p.faq.map(item => `### Q: ${item.q}\n\n${item.a}`).join("\n\n") + `\n\n<script type="application/ld+json">\n${JSON.stringify(faqSchema, null, 2)}\n</script>`;

  return `---
title: "${p.title}"
published: ${p.published}
description: "${p.description}"
image: ""
tags: ${JSON.stringify(p.tags)}
category: "${p.category}"
draft: false
---

> **核心结论先行（Answer-First）：**  
> ${p.answerFirst}

${sectionsContent}

${faqContent}
`;
}

