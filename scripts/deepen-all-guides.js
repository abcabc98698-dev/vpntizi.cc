const postsDir = 'src/content/posts';

function getPublished(file, fallback) {
  const p = path.join(postsDir, file);
  if (fs.existsSync(p)) {
    const c = fs.readFileSync(p, 'utf-8');
    const m = c.match(/published:\s*([^\r\n]+)/);
    if (m) return m[1].trim();
  }
  return fallback;
}

